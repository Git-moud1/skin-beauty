/** Format a price with thousands separators + localized currency word. */
export function formatPrice(amount, lang = "fr") {
  const n = Number(amount) || 0;
  const grouped = n.toLocaleString("en-US"); // Western digits, thousands grouping
  const currency = lang === "ar" ? "أوقية" : "MRU";
  return lang === "ar" ? `${grouped} ${currency}` : `${grouped} ${currency}`;
}

/** Localized date/time for orders. */
export function formatDateTime(value, lang = "fr") {
  try {
    const d = new Date(String(value).replace(" ", "T") + "Z");
    return new Intl.DateTimeFormat(lang === "ar" ? "ar-MR" : "fr-FR", {
      dateStyle: "medium",
      timeStyle: "short",
    }).format(d);
  } catch {
    return String(value);
  }
}
